"""Generates the proxy export table of XivAlexanderLoader64.dll from the named exports of this machine's System32
d3d11.dll, dxgi.dll and dinput8.dll, into this folder:

  ProxyExports.asm  one `jmp qword ptr [slot]` stub per export, and lazy resolvers
  ProxyExports.h    the export names and owning DLLs, in slot order
  Exports64.def     the module definition, keeping the ordinals of the typed forwarders

The five functions with typed forwarders in Proxy.cpp (chain loading as the game used it) are not stubbed.
Usage: python gen_proxy.py
"""
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
DLLS = ("d3d11.dll", "dxgi.dll", "dinput8.dll")
TYPED = {
    "DirectInput8Create": ("FORWARDER_DirectInput8Create", 1),
    "D3D11CreateDevice": ("FORWARDER_D3D11CreateDevice", 5),
    "CreateDXGIFactory": ("FORWARDER_CreateDXGIFactory", 10),
    "CreateDXGIFactory1": ("FORWARDER_CreateDXGIFactory1", 11),
    "CreateDXGIFactory2": ("FORWARDER_CreateDXGIFactory2", 12),
}
OWN = [("XA_InjectEntryPoint", "InjectEntryPoint", 100), ("XA_PatchEntryPoint", "XA_PatchEntryPoint", 101),
       ("InjectEntryPoint", "InjectEntryPoint", None), ("EnableInjectOnCreateProcess", "EnableInjectOnCreateProcess", None),
       ("EnableXivAlexander", "EnableXivAlexander", None), ("DisableAllApps", "DisableAllApps", None), ("CallFreeLibrary", "CallFreeLibrary", None)]


def pe_exports(path):
    """Returns [(name, is_code)] of the named exports, in name order."""
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    magic = struct.unpack_from("<H", data, pe + 24)[0]
    dd = pe + 24 + (112 if magic == 0x20B else 96)
    export_rva = struct.unpack_from("<I", data, dd)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    sec = pe + 24 + opt_size
    sections = [struct.unpack_from("<IIIIIIHHI", data, sec + i * 40 + 8) for i in range(nsec)]

    def section_of(rva):
        for s in sections:
            vsize, vaddr, rsize, raddr = s[0], s[1], s[2], s[3]
            if vaddr <= rva < vaddr + max(vsize, rsize):
                return s
        raise ValueError(hex(rva))

    def off(rva):
        s = section_of(rva)
        return rva - s[1] + s[3]

    e = off(export_rva)
    base, nfuncs, nnames, funcs, names, ords = struct.unpack_from("<IIIIII", data, e + 16)
    result = []
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", data, off(names) + i * 4)[0]
        name = data[off(name_rva):data.index(b"\0", off(name_rva))].decode()
        index = struct.unpack_from("<H", data, off(ords) + i * 2)[0]
        func_rva = struct.unpack_from("<I", data, off(funcs) + index * 4)[0]
        characteristics = section_of(func_rva)[8]
        result.append((name, bool(characteristics & 0x20000000)))  # IMAGE_SCN_MEM_EXECUTE
    return result


def main():
    entries = []  # (dll, name)
    seen = {}
    for dll in DLLS:
        for name, is_code in pe_exports(pathlib.Path(r"C:\Windows\System32") / dll):
            if not is_code:
                sys.exit("%s!%s is not code; a jump stub cannot stand in for it" % (dll, name))
            if name in seen:
                sys.exit("%s is exported by both %s and %s" % (name, seen[name], dll))
            seen[name] = dll
            if name not in TYPED:
                entries.append((dll, name))
    missing = [n for n in TYPED if n not in seen]
    if missing:
        sys.exit("typed forwarders without a System32 export: %s" % missing)

    header = "; Generated by gen_proxy.py from System32 d3d11.dll, dxgi.dll and dinput8.dll; do not edit.\n"
    asm = [header,
           "; Each export jumps through its slot; a slot first points at a resolver that fills it in.",
           "",
           "EXTERN XA_ProxyResolve:PROC",
           "PUBLIC XA_ProxySlots",
           "",
           ".data",
           "ALIGN 8",
           "XA_ProxySlots LABEL QWORD"]
    asm += ["\tDQ XA_ProxyLazy_%d" % i for i in range(len(entries))]
    asm += ["", ".code", ""]
    for i, (dll, name) in enumerate(entries):
        asm += ["XA_Proxy_%s PROC" % name, "\tjmp QWORD PTR [XA_ProxySlots + %d]" % (i * 8), "XA_Proxy_%s ENDP" % name, ""]
    for i in range(len(entries)):
        asm += ["XA_ProxyLazy_%d PROC" % i, "\tmov eax, %d" % i, "\tjmp XA_ProxyLazyCommon", "XA_ProxyLazy_%d ENDP" % i, ""]
    asm += [
        "; Keeps the argument registers across XA_ProxyResolve(index), then continues into the resolved function.",
        "XA_ProxyLazyCommon PROC",
        "\tpush rcx",
        "\tpush rdx",
        "\tpush r8",
        "\tpush r9",
        "\tsub rsp, 68h",
        "\tmovdqu XMMWORD PTR [rsp + 20h], xmm0",
        "\tmovdqu XMMWORD PTR [rsp + 30h], xmm1",
        "\tmovdqu XMMWORD PTR [rsp + 40h], xmm2",
        "\tmovdqu XMMWORD PTR [rsp + 50h], xmm3",
        "\tmov ecx, eax",
        "\tcall XA_ProxyResolve",
        "\tmovdqu xmm0, XMMWORD PTR [rsp + 20h]",
        "\tmovdqu xmm1, XMMWORD PTR [rsp + 30h]",
        "\tmovdqu xmm2, XMMWORD PTR [rsp + 40h]",
        "\tmovdqu xmm3, XMMWORD PTR [rsp + 50h]",
        "\tadd rsp, 68h",
        "\tpop r9",
        "\tpop r8",
        "\tpop rdx",
        "\tpop rcx",
        "\tjmp rax",
        "XA_ProxyLazyCommon ENDP",
        "",
        "END",
        ""]
    (HERE / "ProxyExports.asm").write_text("\n".join(asm), encoding="utf-8", newline="\r\n")

    h = ["#pragma once",
         "",
         "// Generated by gen_proxy.py from System32 d3d11.dll, dxgi.dll and dinput8.dll; do not edit.",
         "",
         "namespace XivAlexander::EntryPoint::ProxyExports {",
         "\tstruct Export {",
         "\t\tconst char* DllName;",
         "\t\tconst char* Name;",
         "\t};",
         "",
         "\t// In the order of XA_ProxySlots in ProxyExports.asm.",
         "\tconstexpr Export Exports[]{"]
    h += ['\t\t{"%s", "%s"},' % (dll, name) for dll, name in entries]
    h += ["\t};", "}", ""]
    (HERE / "ProxyExports.h").write_text("\n".join(h), encoding="utf-8", newline="\r\n")

    d = ["LIBRARY XivAlexanderLoader64", "EXPORTS"]
    d += ["\t%s=%s\t\t@%d" % (name, target, ordinal) for name, (target, ordinal) in sorted(TYPED.items(), key=lambda kv: kv[1][1])]
    d += [""]
    d += ["\t%s=XA_Proxy_%s" % (name, name) for dll, name in entries]
    d += [""]
    d += [("\t%s=%s\t\t@%d" % (name, target, ordinal)) if ordinal else ("\t%s=%s" % (name, target)) for name, target, ordinal in OWN]
    d += [""]
    (HERE / "Exports64.def").write_text("\n".join(d), encoding="utf-8", newline="\r\n")
    counts = {dll: sum(1 for d_, _ in entries if d_ == dll) for dll in DLLS}
    print("stubs:", counts, "typed:", len(TYPED))


main()
